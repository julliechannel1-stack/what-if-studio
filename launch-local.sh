#!/bin/bash
# Local fleet dispatcher (fallback - many hours). Max 3 concurrent renders.
# Usage: bash launch-local.sh <episode> [chunks.json]
# Generates one driver per chunk (render-<ep>-<seg>-<chunk>.sh), launches
# them as detached processes. Drivers verify their chunk on disk and exit
# if it is already good; otherwise they wait for a slot and render.
set -u
EPISODE="${1:?episode slug required}"
SPEC="${2:-chunks-${EPISODE}.json}"
[ -f "$SPEC" ] || SPEC="chunks.json"
cd "$(dirname "$0")"
# cd is its own statement: `cd dir && nohup cmd &` backgrounds the whole chain.
mkdir -p drivers logs out/"$EPISODE" .tmp
export TMPDIR="$PWD/.tmp"
# Archive old render drivers before a new episode's fleet - names like
# render-s03-c1050.sh collide across episodes.
if ls drivers/render-*.sh >/dev/null 2>&1; then
  ARCHIVE="drivers/archive-$(date +%Y%m%d-%H%M%S)"
  mkdir -p "$ARCHIVE"
  mv drivers/render-*.sh "$ARCHIVE"/
  echo "Archived old drivers to $ARCHIVE"
fi
python3 - "$EPISODE" "$SPEC" <<'PYEOF'
import json, sys, pathlib
episode, spec = sys.argv[1], sys.argv[2]
chunks = json.load(open(spec))
for c in chunks:
    seg, chunk, comp, frames, expected = c['seg'], c['chunk'], c['comp'], c['frames'], c['expected']
    driver = pathlib.Path(f"drivers/render-{episode}-{seg}-{chunk}.sh")
    driver.write_text(f'''#!/bin/bash
# Driver for {episode} {seg} {chunk} - generated by launch-local.sh
set -u
OUT="out/{episode}-{seg}/chunks/{chunk}.mp4"
mkdir -p "$(dirname "$OUT")"
if [ -f "$OUT" ]; then
  COUNT=$(ffprobe -v error -select_streams v:0 -count_frames -show_entries stream=nb_read_frames -of default=noprint_wrappers=1:nokey=1 "$OUT" 2>/dev/null || echo "")
  if [ "$COUNT" = "{expected}" ]; then echo "DONE already on disk: $OUT"; exit 0; fi
fi
export TMPDIR="$PWD/.tmp"
while true; do
  if [ -d .slotlock ]; then
    find .slotlock -mmin +1 -exec rmdir {{}} \\; 2>/dev/null || true
  fi
  if mkdir .slotlock 2>/dev/null; then
    pgrep -fc '^node.*remotion render' > logs/pgrep-$$.tmp
    COUNT=$(cat logs/pgrep-$$.tmp)
    rm -f logs/pgrep-$$.tmp
    if [ "$COUNT" -lt 3 ]; then
      rm -f "$OUT"
      REMOTION_BROWSER_EXECUTABLE="$PWD/chrome-with-policy.sh" nohup npx remotion render src/index.ts {comp} "$OUT" --frames={frames} --concurrency 1 --timeout 120000 --log error > logs/render-{episode}-{seg}-{chunk}.log 2>&1 &
      RENDER_PID=$!
      rmdir .slotlock
      wait $RENDER_PID
      RENDER_STATUS=$?
      COUNT=$(ffprobe -v error -select_streams v:0 -count_frames -show_entries stream=nb_read_frames -of default=noprint_wrappers=1:nokey=1 "$OUT" 2>/dev/null || echo "")
      if [ "$COUNT" = "{expected}" ]; then echo "DONE: $OUT"; exit 0; else echo "FAIL {seg} {chunk}: ffprobe=$COUNT expected={expected} render_status=$RENDER_STATUS" >&2; exit 1; fi
    else
      rmdir .slotlock
      sleep 10
    fi
  else
    sleep 5
  fi
done
''')
    driver.chmod(0o755)
    print(f"generated {driver}")
PYEOF
for d in drivers/render-"$EPISODE"-*.sh; do
  nohup bash "$d" > "logs/$(basename "$d" .sh).log" 2>&1 &
  echo "launched $d pid $!"
done
echo "launch-local: launched drivers for $EPISODE from $SPEC (max 3 lanes)"
